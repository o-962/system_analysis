"""Regenerate loader.js with a content hash for every script.

Run this after changing any file in data/ or components/, before committing:

    python update_versions.py

Each file gets ?v=<first 10 chars of its MD5>, so its URL changes exactly when its
content changes. index.html loads loader.js with a timestamp, so even a cached
index.html always picks up the newest file list.
"""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))

# Load order matters: course data first, then normalization (store.jsx), then the UI, then App last.
DATA = ['ch1.js', 'ch2.js', 'ch3.js', 'ch4.js', 'mock.js', 'mock2.js', 'patterns.js']
COMPONENTS = ['store.jsx', 'Quiz.jsx', 'Exam.jsx', 'Chapter.jsx', 'Home.jsx', 'Review.jsx', 'Search.jsx', 'Notes.jsx', 'App.jsx']


def versioned(path):
    with open(os.path.join(ROOT, path), 'rb') as f:
        # Hash with normalized line endings so Windows and Linux checkouts agree.
        digest = hashlib.md5(f.read().replace(b'\r\n', b'\n')).hexdigest()[:10]
    return path + '?v=' + digest


def main():
    data = [versioned('data/' + f) for f in DATA]
    comps = [versioned('components/' + f) for f in COMPONENTS]
    loader = '''/* Generated by update_versions.py. Do not edit by hand.
   Writes the script tags while the page is still parsing, so Babel standalone
   finds the JSX files on DOMContentLoaded exactly as if they were in index.html. */
(function () {
  var data = %s;
  var components = %s;
  var html = '';
  data.forEach(function (src) { html += '<script src="' + src + '"><\\/script>'; });
  components.forEach(function (src) { html += '<script type="text/babel" data-presets="react" src="' + src + '"><\\/script>'; });
  document.write(html);
})();
''' % (json.dumps(data, indent=4), json.dumps(comps, indent=4))
    with open(os.path.join(ROOT, 'loader.js'), 'w', encoding='utf8', newline='\n') as f:
        f.write(loader)
    for p in data + comps:
        print(p)


if __name__ == '__main__':
    main()
